"""
backup_bot.py — Push bot source code to the private solBotCode repo
====================================================================

Daily-ish snapshot of the bot's CODE (not state) to a private GitHub
repo so a hardware failure doesn't lose the strategy work. Mirrors a
curated set of files into ~/Desktop/solBotCode/ then commits + pushes.

NEVER backed up:
  • .env (private key)
  • thebigshortbus-*.json (Google service account)
  • sol_*.json (state — regenerates on its own)
  • _*.json (research scratch — gigabytes of throwaway data)
  • bot_output.log / bot.log / dashboard.log
  • __pycache__/

Run modes:
    python backup_bot.py            # one-shot: copy + commit + push
    python backup_bot.py --dry-run  # show what would be copied/committed
    python backup_bot.py --no-push  # commit locally but skip git push

Wired into degen_bot.py to auto-run once every 24 hours when the bot
is alive. Also safe to run manually any time you want a forced backup.
"""

import os
