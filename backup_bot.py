# ────────────────────────────────────────────────────────────────────────────
# Copy logic — purely additive. Never deletes from the backup repo.
# A removed source file leaves its old backup intact (good — accidental
# deletion in the live tree shouldn't propagate to backup).
# ────────────────────────────────────────────────────────────────────────────


def copy_file_if_present(src: Path, dst: Path, dry_run: bool = False) -> bool:
    if not src.exists() or not src.is_file():
        return False
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dry_run:
        # Compare sizes so dry-run shows what would change
        if dst.exists() and dst.stat().st_size == src.stat().st_size:
            return False  # likely unchanged
        return True
    shutil.copy2(src, dst)
    return True


def copy_all(dry_run: bool = False) -> dict:
    BACKUP_ROOT.mkdir(parents=True, exist_ok=True)
    counts = {"copied": 0, "skipped_missing": 0, "scheduled_tasks": 0}

    # 1. Code + prompts + docs + brain memory
    for filename in CODE_FILES + PROMPT_FILES + DOC_FILES + BRAIN_MEMORY_FILES:
        src = BOT_ROOT / filename
        dst = BACKUP_ROOT / filename
        if copy_file_if_present(src, dst, dry_run):
            counts["copied"] += 1
        elif not src.exists():
            counts["skipped_missing"] += 1

    # 2. Scheduled-task SKILL.md files (live in ~/.claude/, separate location)
    if SCHEDULED_TASKS_DIR.exists():
        for task_dir in SCHEDULED_TASKS_DIR.iterdir():
            skill = task_dir / "SKILL.md"
            if skill.exists():
                dst = BACKUP_ROOT / ".claude" / "scheduled-tasks" / task_dir.name / "SKILL.md"
                if copy_file_if_present(skill, dst, dry_run):
                    counts["scheduled_tasks"] += 1

    # 3. .env.example (synthesized — never has real values)
    env_template = env_example_template()
    if env_template:
        env_dst = BACKUP_ROOT / ".env.example"
        if dry_run:
            counts["copied"] += 1 if not env_dst.exists() or env_dst.read_text(encoding="utf-8") != env_template else 0
        else:
            env_dst.write_text(env_template, encoding="utf-8")
            counts["copied"] += 1

    # 4. Backup .gitignore (always overwrite — it's our safety net)
    if not dry_run:
        (BACKUP_ROOT / ".gitignore").write_text(backup_gitignore(), encoding="utf-8")

    return counts


# ────────────────────────────────────────────────────────────────────────────
# Git operations — only inside BACKUP_ROOT. Never touches the bot's repo.
# ────────────────────────────────────────────────────────────────────────────


_CREATE_NO_WINDOW = 0x08000000 if sys.platform == "win32" else 0


def _git(cmd: list[str], check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(
        cmd, cwd=BACKUP_ROOT, check=check,
        capture_output=True, text=True,
        creationflags=_CREATE_NO_WINDOW,
    )


def commit_and_push(dry_run: bool = False, no_push: bool = False) -> tuple[bool, str]:
    """Returns (success, message)."""
    # Stage everything in the backup repo (the .gitignore protects us from
    # accidentally including secrets that we never copied in).
    _git(["git", "add", "-A"], check=False)

    diff = _git(["git", "diff", "--cached", "--name-only"], check=False)
    changed_files = diff.stdout.strip().splitlines()
    if not changed_files:
        return True, "no changes — backup already up to date"

    msg = f"backup {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}"
    if dry_run:
        return True, f"dry-run: would commit {len(changed_files)} file(s): {', '.join(changed_files[:6])}{'…' if len(changed_files) > 6 else ''}"

    commit = _git(["git", "commit", "-m", msg], check=False)
    if commit.returncode != 0:
        return False, f"commit failed: {commit.stderr.strip()}"

    if no_push:
        return True, f"committed locally ({len(changed_files)} files), --no-push"

    push = _git(["git", "push", "origin", "HEAD"], check=False)
    if push.returncode != 0:
        return False, f"committed but push failed: {push.stderr.strip()}"

    return True, f"backed up {len(changed_files)} file(s) → solBotCode"


# ────────────────────────────────────────────────────────────────────────────


def write_log_entry(success: bool, message: str, counts: dict):
    """Append to sol_backup_log.json so the dashboard / operator can see
    when the last successful backup ran."""
    log_file = BOT_ROOT / "sol_backup_log.json"
    try:
        entries = json.loads(log_file.read_text(encoding="utf-8")) if log_file.exists() else []
    except Exception:
        entries = []
    entries.append({
        "ts": datetime.now().strftime("%Y-%m-%d %H:%M:%S EDT"),
        "ok": success,
        "message": message,
        "counts": counts,
    })
    # Keep last 100 entries to bound size
    entries = entries[-100:]
    log_file.write_text(json.dumps(entries, indent=2), encoding="utf-8")


def main():
    args = sys.argv[1:]
    dry_run = "--dry-run" in args
    no_push = "--no-push" in args

    if not BACKUP_ROOT.exists():
        print(f"ERROR: backup repo not cloned at {BACKUP_ROOT}")
        print(f"Run first: cd {BACKUP_ROOT.parent} && git clone https://github.com/JPMendenhall/solBotCode.git")
        sys.exit(1)

    print(f"[backup] source: {BOT_ROOT}")
    print(f"[backup] target: {BACKUP_ROOT}")
    print(f"[backup] mode:   {'dry-run' if dry_run else ('no-push' if no_push else 'commit+push')}")

    counts = copy_all(dry_run=dry_run)
    print(f"[backup] copied: {counts['copied']} files (+ {counts['scheduled_tasks']} scheduled-task SKILL.md)")
    if counts["skipped_missing"]:
        print(f"[backup] skipped (not present locally): {counts['skipped_missing']}")

    success, message = commit_and_push(dry_run=dry_run, no_push=no_push)
    print(f"[backup] {message}")

    if not dry_run:
        write_log_entry(success, message, counts)

    sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()
